/**
 * Returns an inline SVG string for the named icon.
 */
export function icon(name, { size = '1.1em', className = '', strokeWidth = 2 } = {}) {
  const body = PATHS[name];
  if (!body) {
    console.warn(`[icons] Unknown icon "${name}"`);
    return '';
  }
  const cls = `icon icon-${name}${className ? ' ' + className : ''}`;
  return `<svg class="${cls}" xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false" style="vertical-align:middle; display:inline-block;">${body}</svg>`;
}

/**
 * Replaces every <i data-icon="name" [data-size="1.2em"]></i> under `root`
 * with the matching inline SVG.
 */
export function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => {
    const svg = icon(el.dataset.icon, { size: el.dataset.size || '1.1em' });
    if (svg) el.outerHTML = svg;
  });
}

/**
 * Turns ":icon-name:" tokens in chat text into inline SVGs.
 */
export function replaceIconTokens(text) {
  return text.replace(/:([a-z][a-z-]*):/g, (match, name) => (PATHS[name] ? icon(name) : match));
}

// Auto-hydrate static markup once the DOM is ready.
if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => hydrateIcons());
  } else {
    hydrateIcons();
  }
}
